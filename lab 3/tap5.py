# Екі бүтін санды енгізу
num1 = int(input("Бірінші санды енгізіңіз: "))
num2 = int(input("Екінші санды енгізіңіз: "))

# Вложенные условия қолдану
if num1 == num2:
    print("Берілген екі сан өзара тең.")
else:
    if num1 > num2:
        print(f"Үлкен сан: {num1}")
    else:
        print(f"Үлкен сан: {num2}")
