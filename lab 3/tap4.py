# 1-ден 100-ге дейінгі ұпайды енгізу
score = int(input("Ұпайыңызды енгізіңіз (1-100 аралығында): "))

# Диапазонның дұрыстығын тексеру
if 1 <= score <= 100:
    if score >= 90:
        print("Бағасы: «A»")
    elif score >= 75:
        print("Бағасы: «B»")
    elif score >= 60:
        print("Бағасы: «C»")
    else:
        print("Бағасы: «D»")
else:
    print("Қате: 1 мен 100 аралығындағы санды енгізіңіз!")
