# Жасты және студенттік билеттің барын сұрау
age = int(input("Жасыңызды енгізіңіз: "))
has_student_card = input("Студенттік билетіңіз бар ма? (иә/жоқ): ").strip().lower()

# Логикалық шарт (18-ден кіші немесе студент болса)
if age < 18 or has_student_card == "иә":
    print("Құттықтаймыз, сізге жеңілдік тариф қарастырылған!")
else:
    print("Сізге стандартты тариф қолданылады.")
